#!/usr/bin/env python3
"""Regenerates what CZebkit derives from the zebkit submodule.

    Scripts/generate.py

Reads Vendor/zebkit (headers, VERSION, the Rust crate's engines.txt) and
writes, in Sources/CZebkit:

    trampolines.c   a definition of every function the headers declare, which
                    calls the function of the same name in the engine
    include/zebkit_symbols.h
                    the names the linker knows those definitions by
    release.h       the version the headers are of, and its archives' SHA-256

Run it after moving the submodule to another release. It needs clang, for
its JSON dump of the headers' declarations.
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "Vendor" / "zebkit"
TARGET = ROOT / "Sources" / "CZebkit"
# The targets a Swift toolchain and a released engine both exist for.
TARGETS = ["aarch64-apple-darwin", "x86_64-unknown-linux-gnu"]


def declarations():
    """Every zebkit function CZebkit.h declares: (name, return type, parameter types)."""
    # CZebkit.h includes a file this script writes: empty will do to read the rest.
    (TARGET / "include" / "zebkit_symbols.h").touch()
    dump = subprocess.run(
        ["clang", "-x", "c", "-std=c11", "-fsyntax-only", "-Xclang", "-ast-dump=json",
         "-I", str(TARGET / "include"), str(TARGET / "include" / "CZebkit.h")],
        check=True, capture_output=True, text=True).stdout
    functions = {}
    for node in json.loads(dump)["inner"]:
        name = node.get("name", "")
        if node.get("kind") != "FunctionDecl" or not name.startswith("zebkit_"):
            continue
        signature = node["type"]["qualType"]
        if node.get("variadic") or signature.endswith("...)"):
            sys.exit(f"{name} is variadic: a trampoline cannot forward it")
        functions[name] = (return_type(signature), [
            child["type"]["qualType"] for child in node.get("inner", []) if child["kind"] == "ParmVarDecl"])
    return sorted(functions.items())


def return_type(signature):
    """`T` of clang's `T (parameters)`: what is before the last group of parentheses."""
    depth = 0
    for index in range(len(signature) - 1, -1, -1):
        depth += {")": 1, "(": -1}.get(signature[index], 0)
        if depth == 0:
            return signature[:index].strip()
    sys.exit(f"unexpected function type: {signature}")


def trampolines(functions, tag):
    lines = [
        f"/* Generated by Scripts/generate.py from zebkit {tag}. Do not edit. */",
        "",
        "#include <stdbool.h>",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        '#include "CZebkit.h"',
        '#include "loader_internal.h"',
        "",
        "/* The engine's function @name, found on first use and kept. */",
        "#define ZK_ENGINE(name)                                                        \\",
        "    ({                                                                         \\",
        "        __typeof__(name) *function = __atomic_load_n(&engine_##name, __ATOMIC_RELAXED); \\",
        "        if (__builtin_expect(!function, 0)) {                                  \\",
        "            function = (__typeof__(name) *)zk_engine_require(#name);           \\",
        "            __atomic_store_n(&engine_##name, function, __ATOMIC_RELAXED);      \\",
        "        }                                                                      \\",
        "        function;                                                              \\",
        "    })",
        "",
    ]
    for name, (result, parameters) in functions:
        declared = ", ".join(f"__typeof__({kind}) a{index}" for index, kind in enumerate(parameters)) or "void"
        passed = ", ".join(f"a{index}" for index in range(len(parameters)))
        returns = "" if result == "void" else "return "
        lines += [
            f"static __typeof__({name}) *engine_{name};",
            f"__typeof__({result}) {name}({declared}) {{ {returns}ZK_ENGINE({name})({passed}); }}",
            "",
        ]
    return "\n".join(lines)


def symbols(functions, tag):
    lines = [
        f"/* Generated by Scripts/generate.py from zebkit {tag}. Do not edit. */",
        "",
        "/*",
        " * The functions <zebkit/...> declare are defined in this module, as",
        " * trampolines into the engine. Under the engine's own names they would be",
        " * second definitions of its symbols in the process, and where the dynamic",
        " * linker has one namespace for all of them (ELF) the engine's library could",
        " * be bound to them in place of its own. So the linker knows each by another",
        " * name, zk_<name>, while C and Swift go on calling it <name>.",
        " */",
        "",
        "#ifndef CZEBKIT_SYMBOLS_H",
        "#define CZEBKIT_SYMBOLS_H",
        "",
    ]
    lines += [f"#pragma redefine_extname {name} zk_{name}" for name, _ in functions]
    lines += ["", "#endif /* CZEBKIT_SYMBOLS_H */", ""]
    return "\n".join(lines)


def release(version):
    checksums = {}
    for line in (UPSTREAM / "bindings/rust/zebkit-rs/engines.txt").read_text().splitlines():
        fields = line.split()
        if len(fields) == 3 and fields[0] == version:
            checksums[fields[1]] = fields[2]
    missing = [target for target in TARGETS if target not in checksums]
    if missing:
        sys.exit(f"engines.txt has no zebkit {version} for {', '.join(missing)}")
    lines = [
        f"/* Generated by Scripts/generate.py from zebkit {version}. Do not edit. */",
        "",
        "#ifndef CZEBKIT_RELEASE_H",
        "#define CZEBKIT_RELEASE_H",
        "",
        f'#define ZK_RELEASE_VERSION "{version}"',
        "",
        "/* target, SHA-256 of zebkit-<version>-<target>.tar.xz */",
        "#define ZK_RELEASE_ARCHIVES \\",
    ]
    lines += [f'    {{"{target}", "{checksums[target]}"}}, \\' for target in TARGETS]
    lines += ["    {NULL, NULL}", "", "#endif /* CZEBKIT_RELEASE_H */", ""]
    return "\n".join(lines)


def main():
    if not (UPSTREAM / "VERSION").exists():
        sys.exit("Vendor/zebkit is empty: git submodule update --init")
    version = (UPSTREAM / "VERSION").read_text().strip()
    tag = subprocess.run(["git", "-C", str(UPSTREAM), "describe", "--tags", "--always"],
                         capture_output=True, text=True).stdout.strip() or version
    functions = declarations()
    (TARGET / "trampolines.c").write_text(trampolines(functions, tag))
    (TARGET / "include" / "zebkit_symbols.h").write_text(symbols(functions, tag))
    (TARGET / "release.h").write_text(release(version))
    print(f"zebkit {version} ({tag}): {len(functions)} functions")


if __name__ == "__main__":
    main()
